const LEGACY_OCCASION_MAP: Record<string, GiftThemePresetId> = {
  'nossa-historia': 'amor-casal',
  vozes: 'amizade',
  especial: 'aniversario',
};

export function getGiftThemePreset(id?: string | null): GiftThemePreset | undefined {
  if (!id) return undefined;
  const normalizedId = LEGACY_OCCASION_MAP[id] || id;
  return GIFT_THEME_PRESETS.find((preset) => preset.id === normalizedId || preset.occasionId === normalizedId);
}

export function applyThemePresetToContent(content: GiftContentData, preset: GiftThemePreset): GiftContentData {
  return {
    ...content,
    themePresetId: preset.id,
    openingText: {
      headline: preset.defaultTexts.openingHeadline,
      description: preset.defaultTexts.openingDescription,
      buttonLabel: preset.defaultTexts.buttonLabel,
    },
    recipient: {
      ...content.recipient,
      subtitle: preset.defaultTexts.recipientSubtitle,
      tagline: preset.defaultTexts.recipientTagline,
      introQuote: preset.defaultTexts.introQuote,
    },
    sectionCopy: preset.sectionCopy,
    soundtrack: content.soundtrack
      ? {
          ...content.soundtrack,
          title: preset.sectionCopy.soundtrack.defaultTitle,
          message: preset.sectionCopy.soundtrack.defaultMessage,
        }
      : content.soundtrack,
    closing: {
      headline: preset.defaultTexts.closingHeadline,
      message: preset.defaultTexts.closingMessage,
      signature: preset.defaultTexts.closingSignature,
    },
  };
}

export function themeFromPreset(preset: GiftThemePreset): Partial<GiftThemeData> {
  return {
    presetId: preset.id,
    styleId: preset.recommendedStyleId,
    primaryColor: preset.palette.primary,
    secondaryColor: preset.palette.secondary,
    accentColor: preset.palette.accent,
    backgroundColor: preset.palette.background,
    surfaceColor: preset.palette.surface,
    textColor: preset.palette.text,
    mutedColor: preset.palette.muted,
    borderColor: preset.palette.border,
  };
}
