// Mapeamento de retrocompatibilidade para slugs e identificadores legados
const THEME_ALIASES: Record<string, string> = {
  'infantil-pokemon': 'infantil-monstrinhos-elementais',
  'infantil-herois': 'infantil-herois-originais',
  'infantil-princesas': 'infantil-reino-encantado',
  'infantil-kpop': 'infantil-pop',
  'infantil-pixel-games': 'infantil-aventura-blocos',
};

export function getThemeById(themeId?: string): AuthorialThemeDefinition {
  if (!themeId) return INVITATION_AUTHORIAL_THEMES[0];
  const normalizedId = THEME_ALIASES[themeId] || themeId;
  return (
    INVITATION_AUTHORIAL_THEMES.find((t) => t.id === normalizedId) ||
    INVITATION_AUTHORIAL_THEMES[0]
  );
}
