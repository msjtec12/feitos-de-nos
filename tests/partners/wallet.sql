-- Run after the partner migration. All fixtures are rolled back, including auth users.
begin;
do $$
declare a uuid:=gen_random_uuid(); b uuid:=gen_random_uuid(); admin_id uuid:=gen_random_uuid();
  oid uuid:=gen_random_uuid(); cancelled uuid:=gen_random_uuid(); inv uuid:=gen_random_uuid();
  p public.partner_profiles; o public.partner_orders; failed boolean; initial_content jsonb;
begin
  insert into auth.users(id,email) values(a,'test-partner-a-'||a||'@example.invalid'),(b,'test-partner-b-'||b||'@example.invalid'),(admin_id,'test-owner-'||admin_id||'@example.invalid');
  insert into public.admin_profiles(id,name,role,active) values(admin_id,'Rollback test owner','owner',true);
  insert into public.partner_profiles(id,store_name,slug,phone,status) values(a,'Rollback Store A','rollback-a-'||a,'5511999999999','active'),(b,'Rollback Store B','rollback-b-'||b,'5511999999999','active');
  assert not has_table_privilege('anon','public.partner_orders','select'), 'Anonymous can read orders';
  assert not has_table_privilege('authenticated','public.partner_profiles','update'), 'Clients can mutate balances';
  assert not has_function_privilege('authenticated','public.partner_credit(uuid,integer,text,uuid)','execute'), 'Clients can credit wallets';
  assert not has_function_privilege('anon','public.partner_create_order(uuid,uuid,text,text)','execute'), 'Anonymous can create orders';
  p:=public.partner_credit(a,10000,'test-credit-'||a,admin_id);
  p:=public.partner_credit(a,10000,'test-credit-'||a,admin_id);
  assert p.balance_cents=10000, 'Credit was duplicated';
  failed:=false;
  begin perform public.partner_credit(a,10000,'test-credit-'||a,b); exception when others then failed:=true; end;
  assert failed,'Non-owner credited a wallet';
  failed:=false;
  begin perform public.partner_credit(a,20000,'test-credit-'||a,admin_id); exception when others then failed:=true; end;
  assert failed,'Conflicting credit reference accepted';
  o:=public.partner_create_order(a,oid,'gift','Test gift');
  o:=public.partner_create_order(a,oid,'gift','Test gift');
  select * into p from public.partner_profiles where id=a;
  assert p.reserved_cents=990 and p.balance_cents=10000,'Duplicate order reserved twice';
  failed:=false;
  begin perform public.partner_create_order(b,gen_random_uuid(),'gift','No balance'); exception when others then failed:=true; end;
  assert failed,'Allowed purchase without funds';
  failed:=false;
  begin perform public.partner_order_action(b,oid,'cancel'); exception when others then failed:=true; end;
  assert failed,'Cross-store mutation allowed';
  initial_content:='{"title":"Test gift","message":"A test message","consent":true}'::jsonb;
  o:=public.partner_order_action(a,oid,'save',initial_content,0,1);
  failed:=false;
  begin perform public.partner_order_action(a,oid,'save',initial_content,0,1); exception when others then failed:=true; end;
  assert failed,'Stale revision overwrote content';
  o:=public.partner_order_action(a,oid,'rotate');
  failed:=false;
  begin perform public.partner_order_action(a,oid,'publish',null,1,1); exception when others then failed:=true; end;
  assert failed,'Revoked edit version published';
  o:=public.partner_order_action(a,oid,'publish',null,1,2);
  o:=public.partner_order_action(a,oid,'publish',null,1,2);
  select * into p from public.partner_profiles where id=a;
  assert p.balance_cents=9010 and p.reserved_cents=0,'Publication charged more than once';
  assert o.expires_at between now()+interval '364 days' and now()+interval '367 days','Gift retention wrong';
  o:=public.partner_order_action(a,oid,'save',initial_content||'{"message":"Corrected text"}'::jsonb,1,2);
  select * into p from public.partner_profiles where id=a;
  assert p.balance_cents=9010,'Correction charged again';
  failed:=false;
  begin perform public.partner_order_action(a,oid,'cancel'); exception when others then failed:=true; end;
  assert failed,'Published order cancelled';
  o:=public.partner_create_order(a,cancelled,'invitation','Cancel me');
  o:=public.partner_order_action(a,cancelled,'cancel');
  o:=public.partner_order_action(a,cancelled,'cancel');
  select * into p from public.partner_profiles where id=a;
  assert p.balance_cents=9010 and p.reserved_cents=0,'Cancellation changed balance or double released';
  failed:=false;
  begin perform public.partner_order_action(a,cancelled,'publish',null,0); exception when others then failed:=true; end;
  assert failed,'Cancelled order published';
  o:=public.partner_create_order(a,inv,'invitation','Test invitation');
  o:=public.partner_order_action(a,inv,'save',initial_content||jsonb_build_object('eventAt',now()+interval '60 days'),0);
  o:=public.partner_order_action(a,inv,'publish',null,1);
  assert o.expires_at=now()+interval '90 days','Invitation retention wrong';
  select * into p from public.partner_profiles where id=a;
  assert p.balance_cents=6020 and p.reserved_cents=0,'Final wallet mismatch';
  assert (select count(*) from public.partner_wallet_entries where partner_id=a)=7,'Ledger entry count mismatch';
end $$;
select 'All wallet, ownership, idempotency, revision and retention assertions passed' as result;
rollback;
